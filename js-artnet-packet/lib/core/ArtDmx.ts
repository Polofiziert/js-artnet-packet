/*
                    00000001 00000010  (258)
Bitwise AND ->    & 00000000 11111111  (0xff / 255)
                    -------------------
                    00000000 00000010  (2)
 */

/*
                       00000000 00000010  (2)       net
Bitshift by 8 ->  << 8 00000010 00000000  (512)     net

                       00000010 00000000  (512)     subUni
Bitwise OR ->        | 00000000 00010011  (19)      subUni
                       --------------------
                       00000010 00010011  (531 / 0x0213) Port-Address
*/

import { ArtnetPacket, writeHeader, checkHeader } from "./ArtnetPacket.ts";
import { OpCode } from './constants.ts'


export class ArtDmx extends ArtnetPacket {
    readonly type = 'ArtDmx' as const

    /**
     * Decodes the buffer if its correct and returns a new ArtDmx Obj if so.
     * The new ArtDmx Object owns the given Buffer!
     * @param buf the Buffer to decode into a Packet
     * @returns {ArtDmx | null} - a new ArtDmx Object or null if the buffer was wrong.
     */
    static decode(buf: Buffer): ArtDmx | null {
        return checkHeader(buf, OpCode.ArtDmx, 18) ? new ArtDmx(buf) : null
    }

    /**
     * Creates a new ArtDmx Obj with given input Data and returns it.
     * The new ArtDmx Obj has a new Buffer that it owns.
     * @param opts Object of the options.
     * @returns ArtDmx or null if options are malformed.
     */
    static create(opts: { net?: number; subUni?: number; physical?: number ; sequence?: number; data: Uint8Array }): ArtDmx | null {
        const len = opts.data.length;                   // gerade Zahl, 2..512
        if (len >= 2 && len <= 512) {
            const buf = Buffer.alloc(18 + len);
            writeHeader(buf, OpCode.ArtDmx);
            buf.writeUInt16BE(len, 16);
            buf.set(opts.data, 18);

            const pkt = new ArtDmx(buf);
            pkt.sequence = opts.sequence ?? 0;
            pkt.net = opts.net ?? 0;
            pkt.subUni = opts.subUni ?? 0;
            return pkt;
        }
        return null;
    }

    // Getter/Setter: lesen und schreiben direkt im Buffer

    /**
     * Gets the Sequence-Number of the artDmx Packet.
     * Reads from the Buffer.
     *
     * @returns number
     */
    get sequence(): number {
        return this.buffer[12];
    }

    /**
     * Sets the Sequence-Number of the artDmx Packet.
     * Written and stored in the Buffer.
     * @param sequenceNumber The incrementing Number of the artDmx Packet in the Sequence of artDmx Packets that it is sent in.
     */
    set sequence(sequenceNumber: number) {
        let hexMask = 0xff;
        this.buffer[12] = sequenceNumber & hexMask; // Capping the sequence value between 0-255; 0x00 and 0xff; using a bitwise AND operation.
    }

    /**
     * Gets the Physical-Number of the artDmx Packet.
     * The physical input port from which DMX512 data was input.
     *
     * This field is used by the receiving device to discriminate between packets with
     * identical Port-Address that have been generated by different input ports and so need to be merged.
     * Reads from the Buffer.
     *
     * @returns number
     */
    get physical(): number {
        return this.buffer[13];
    }

    /**
     * Sets the physical-Number of the artDmx Packet.
     *
     * This field is used by the receiving device to discriminate between packets with
     * identical Port-Address that have been generated by different input ports and so need to be merged.
     * Written and stored in the Buffer.
     * @param physicalNumber The physical input port from which DMX512 data was input.
     */
    set physical(physicalNumber: number) {
        let hexMask = 0xff;
        this.buffer[13] = physicalNumber & hexMask; // Capping the sequence value between 0-255; 0x00 and 0xff; using a bitwise AND operation.
    }

    /**
     * Gets the subUni (sub-net + universe) of the artDmx Packet.
     * The low byte of the 15 bit Port-Address to which this packet is destined.
     * Reads from the Buffer.
     *
     * @returns number
     */
    get subUni(): number {
        return this.buffer[14];
    }

    /**
     * Sets the sub subUni (sub-net + universe) of the artDmx Packet.
     * Written and stored in the Buffer.
     * @param subUniNumber The low byte of the 15 bit Port-Address to which this packet is destined.
     */
    set subUni(subUniNumber: number) {
        let hexMask = 0xff;
        this.buffer[14] = subUniNumber & hexMask; // Capping the sequence value between 0-255; 0x00 and 0xff; using a bitwise AND operation.
    }

    /**
     * Gets the net-Number of the artDmx Packet.
     * The top 7 bits of the 15 bit Port-Address to which this packet is destined.
     * Reads from the Buffer.
     *
     * @returns number
     */
    get net(): number {
        return this.buffer[15];
    }

    /**
     * Sets the net-Number of the artDmx Packet.
     * Written and stored in the Buffer.
     * @param netNumber The top 7 bits of the 15 bit Port-Address to which this packet is destined.
     */
    set net(netNumber: number) {
        let hexMask = 0x7f;
        this.buffer[15] = netNumber & hexMask; // Capping the sequence value between 0-127; 0x00 and 0x7f; using a bitwise AND operation.
    }

    /**
     * Gets the Port-Address of the artDmx Packet.
     * The 15 bit Address of the destination Port.
     *
     * One of the 32,768 possible addresses to which a DMX frame can be
     * directed. The Port-Address is a 15-bit number composed of Net+Sub-Net+Universe.
     * Reads net+subUni (net + sub-net + universe) from the Buffer.
     *
     *     Bit 15 | Bits 14-8 | Bits 7-4 | Bits 3-0
     *     0      | Net       | Sub-Net  | Universe
     *     => Port-Address
     *
     * @returns number
     */
    get portAddress(): number {
        return (this.net << 8) | this.subUni;
    }

    /**
     * Converts the given Port-Address to the Net and SubUni of
     * the artDmx Packet and sets them.
     * Written and stored in the Buffer.
     *
     * One of the 32,768 possible addresses to which a DMX frame can be
     * directed. The Port-Address is a 15-bit number composed of Net+Sub-Net+Universe.
     * Reads net+subUni (net + sub-net + universe) from the Buffer.
     *
     *     Bit 15 | Bits 14-8 | Bits 7-4 | Bits 3-0
     *     0      | Net       | Sub-Net  | Universe
     *     => Port-Address
     *
     * @param portAddress The Address of the destination Port. Between 1 - 32,768.
     */
    set portAddress(portAddress: number) {
        if (portAddress <= 32767) {
            let hexMask = 0xff;

            let net = portAddress >> 8; // move the last bits to the front, deletes the first bits.
            let subUni = portAddress & hexMask; // clamps the value to 0-255 so the last bits get deleted.

            this.net = net;
            this.subUni = subUni;
        }
    }

    // wirft nie, begrenzt auf die tatsächlich vorhandene Länge
    /**
     * Gets the number of DMX512 channels encoded in the packet.
     * Value must be between 2 - 512.
     *
     * The length of the DMX512 data array.
     * NB: Products which convert Art-Net to DMX512 may opt to always send 512 channels.
     *
     * @returns number
     */
    get length(): number {
        return Math.min(this.buffer.readUInt16BE(16), this.buffer.length - 18);
    }

    /**
     * Gets the DMX512 channels encoded in the Packet.
     * The returned Buffer is a new one, not owned by the Packet.
     *
     * @returns Buffer
     */
    get data(): Buffer {
        return this.buffer.subarray(18, 18 + this.length);
    }

    set data(channels: Uint8Array) {
        if(channels.length >= 2 && channels.length <= 512) {
            this.buffer.set(channels, 18);
        }
    }

    toJSON(key: string){
        if(key){
            return key;
        }else{
            let plainObject = {
                type: "ArtDmx",
                sequence: this.sequence,
                physical: this.physical,
                net: this.net,
                subUni: this.subUni,
                portAddress: this.portAddress,
                length: this.length,
                data: this.data
            }
            return plainObject;
        }
    }

}